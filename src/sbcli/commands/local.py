"""local: run a full Supabase stack on this machine (Supabase CLI → Docker / Podman containers)."""

from __future__ import annotations

import shutil
import subprocess
import webbrowser
from pathlib import Path

import typer

from sbcli.config import project_root, write_state
from sbcli.errors import CliError
from sbcli.output import console, info, ok, warn

local_app = typer.Typer(help="Local Supabase stack in containers (wraps the Supabase CLI).", no_args_is_help=True)

# services that are nice-to-have but heavy (and the usual podman troublemakers)
LEAN_EXCLUDES = "edge-runtime,logflare,vector,imgproxy"

# `supabase status -o env` key  →  our .env key   (first match wins)
ENV_MAP = {
    "SUPABASE_URL": ("API_URL",),
    "SUPABASE_ANON_KEY": ("ANON_KEY", "PUBLISHABLE_KEY"),
    "SUPABASE_SERVICE_ROLE_KEY": ("SERVICE_ROLE_KEY", "SECRET_KEY"),
    "DATABASE_URL": ("DB_URL",),
}


def _supabase_cmd() -> list[str]:
    if shutil.which("supabase"):
        return ["supabase"]
    if shutil.which("npx"):
        return ["npx", "--yes", "supabase"]
    raise CliError(
        "Supabase CLI not found. Install it:\n"
        "  macOS:  brew install supabase/tap/supabase\n"
        "  any:    npm i -g supabase   (or use npx)\n"
        "and a container runtime (Docker Desktop, OrbStack, Colima or Podman)."
    )


def _run(*args: str, capture: bool = False) -> subprocess.CompletedProcess:
    cmd = _supabase_cmd() + list(args)
    info("$ " + " ".join(cmd))
    return subprocess.run(cmd, cwd=project_root(), text=True, stdin=subprocess.DEVNULL,
                          capture_output=capture, check=False)


def _ensure_init() -> None:
    config = project_root() / "supabase" / "config.toml"
    if not config.exists():
        r = _run("init")
        if r.returncode != 0:
            raise CliError("`supabase init` failed")
        ok("supabase/config.toml created")


def _parse_env(text: str) -> dict[str, str]:
    out = {}
    for line in text.splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip().strip('"')
    return out


def write_env_local() -> Path:
    r = _run("status", "-o", "env", capture=True)
    if r.returncode != 0:
        raise CliError(f"`supabase status` failed — is the stack running?\n{r.stderr.strip()}")
    status = _parse_env(r.stdout)
    lines = ["# generated by `sbcli local env` — safe to regenerate", ""]
    for ours, theirs in ENV_MAP.items():
        value = next((status[k] for k in theirs if status.get(k)), None)
        if value:
            lines.append(f"{ours}={value}")
        else:
            warn(f"{ours}: none of {theirs} in `supabase status` output")
    if status.get("STUDIO_URL"):
        lines.append(f"# Studio: {status['STUDIO_URL']}")
    target = project_root() / ".env.local"
    target.write_text("\n".join(lines) + "\n")
    return target


@local_app.command("init")
def init():
    """Create supabase/config.toml (once)."""
    _ensure_init()


@local_app.command("start")
def start(
    lean: bool = typer.Option(False, "--lean", help=f"Skip {LEAN_EXCLUDES} (lighter, podman-friendly)."),
    env: bool = typer.Option(True, "--env/--no-env", help="Write .env.local afterwards."),
):
    """Start the stack (first start pulls the images — get a coffee ☕)."""
    _ensure_init()
    args = ["start"] + (["-x", LEAN_EXCLUDES] if lean else [])
    if _run(*args).returncode != 0:
        raise CliError("`supabase start` failed. Is Docker/Podman running? (see README → Local stack)")
    if env:
        path = write_env_local()
        write_state(target="local")
        ok(f"{path.name} written, default target = local")
    console.print("Next: [bold]uv run sbcli db reset -y[/bold]  then  "
                  "[bold]uv run sbcli users add you@example.com[/bold]")


@local_app.command("stop")
def stop(wipe: bool = typer.Option(False, "--wipe", help="Also delete the volumes (all local data).")):
    """Stop the stack (data survives unless --wipe)."""
    _run("stop", *(["--no-backup"] if wipe else []))


@local_app.command("status")
def status():
    """URLs, keys and container state."""
    _run("status")


@local_app.command("env")
def env():
    """(Re)write .env.local from `supabase status`."""
    path = write_env_local()
    ok(f"{path} written")


@local_app.command("studio")
def studio():
    """Open Supabase Studio in the browser."""
    url = "http://127.0.0.1:54323"
    webbrowser.open(url)
    ok(f"Studio: {url}   ·   Mailpit (auth mails): http://127.0.0.1:54324")
