create table mobappdata.categories (
  id    integer generated by default as identity primary key,
  name  varchar(100) not null check (btrim(name) <> '')
);
create unique index categories_name_unique on mobappdata.categories (lower(name));
comment on table mobappdata.categories is 'Product categories.';

create table mobappdata.products (
  id           integer generated by default as identity primary key,
  name         varchar(100)   not null check (btrim(name) <> ''),
  category_id  integer        references mobappdata.categories (id),   -- nullable: "no category"
  unit         varchar(20)    not null check (unit <> '' and unit = upper(unit)),
  price        decimal(12, 2) not null default 0.00 check (price >= 0),
  vat          decimal(6, 2)  not null default 0.19 check (vat >= 0 and vat < 1)
);
create index products_category_idx  on mobappdata.products (category_id);
create index products_name_trgm_idx on mobappdata.products using gin (name extensions.gin_trgm_ops);

comment on table  mobappdata.products       is 'Products. price = shelf price incl. VAT (gross).';
comment on column mobappdata.products.unit  is 'PC = piece, PK = pack, KG = kilogram, … (upper case)';
comment on column mobappdata.products.vat   is 'VAT rate as fraction: 0.07 = 7 %, 0.19 = 19 %.';

-- Keep the identity sequences ahead of explicitly inserted ids (data script,
-- imports). Called after every bulk insert with explicit ids.
create or replace function mobappdata.sync_id_sequences()
returns void
language sql
set search_path = ''
as $$
  select setval(pg_get_serial_sequence('mobappdata.categories', 'id'),
                greatest(coalesce((select max(id) from mobappdata.categories), 0), 1),
                (select count(*) > 0 from mobappdata.categories));
  select setval(pg_get_serial_sequence('mobappdata.products', 'id'),
                greatest(coalesce((select max(id) from mobappdata.products), 0), 1),
                (select count(*) > 0 from mobappdata.products));
$$;
